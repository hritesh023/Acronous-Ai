function parseResults(items) {
  return items.slice(0, 5).map(r => {
    const title = r.title || '';
    const content = (r.content || r.snippet || '').slice(0, 200);
    return `- ${title}${content ? `: ${content}` : ''}`;
  }).filter(Boolean).join('\n');
}

